"""Classifier types, detection models, and score band definitions.

Important note on calibration:
Model output values from uncalibrated multi-label classifiers (such as YAMNet)
represent raw activation values, NOT true posterior probabilities. We categorize
them into documented qualitative score bands and clearly convey acoustic uncertainty.
"""
from enum import Enum
from pydantic import BaseModel, ConfigDict, Field


class ScoreBand(str, Enum):
    """Documented qualitative bands for raw acoustic activation scores.
    
    These bands intentionally avoid claiming certainty or statistical probability.
    """
    STRONG_SIGNAL = "STRONG_SIGNAL"         # Raw score >= 0.50
    MODERATE_SIGNAL = "MODERATE_SIGNAL"     # 0.25 <= Raw score < 0.50
    SUGGESTIVE_TRACE = "SUGGESTIVE_TRACE"   # 0.10 <= Raw score < 0.25


def map_score_to_band(raw_score: float) -> ScoreBand:
    """Map a raw score [0.0, 1.0] to a documented qualitative score band."""
    if raw_score >= 0.50:
        return ScoreBand.STRONG_SIGNAL
    elif raw_score >= 0.25:
        return ScoreBand.MODERATE_SIGNAL
    else:
        return ScoreBand.SUGGESTIVE_TRACE


class Detection(BaseModel):
    """An acoustic event detected during an interval of audio.
    
    All detections carry honest metadata indicating the model source and score band.
    """
    start_time: float = Field(..., ge=0.0, description="Start offset in seconds")
    end_time: float = Field(..., ge=0.0, description="End offset in seconds")
    label: str = Field(..., description="Human-readable acoustic event name")
    raw_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Raw model activation output [0.0, 1.0]. Not a calibrated probability.",
    )
    score_band: ScoreBand = Field(
        ...,
        description="Qualitative signal band based on documented thresholds.",
    )
    model_id: str = Field(..., description="Identifier of the model that produced this detection")
    model_version: str = Field(..., description="Version or checkpoint tag of the model")
    is_test_fixture: bool = Field(
        default=False,
        description="True if generated by a fake adapter or mock test suite, false for real AI inference.",
    )
    scientific_disclaimer: str = Field(
        default="Acoustic detections reflect model activations and may be inaccurate or confused by ambient noise.",
        description="Explicit user-facing scientific limitation reminder.",
    )

    model_config = ConfigDict(frozen=True)
